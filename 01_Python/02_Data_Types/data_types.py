# Data Types
# Integer and Float

age = 22
salary = 80000.50

print("Age:", age)
print("Salary:", salary)

print("Type of age:", type(age))
print("Type of salary:", type(salary))

# String and Boolean

name = "Swarup"
is_working = True

print("Name:", name)
print("Working:", is_working)

print("Type of name:", type(name))
print("Type of is_working:", type(is_working))

# Type Conversion

name = "Swarup"
is_working = True

print("Name:", name)
print("Working:", is_working)

print("Type of name:", type(name))
print("Type of is_working:", type(is_working))



